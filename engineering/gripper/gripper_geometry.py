"""RobotTwin — parametric geometry for the parallel-jaw gripper (v2, servo).

Pure Python, importable anywhere (no Fusion dependency): this module IS the
parametric layer, in the same architecture as
engineering/fusion/robot_linkages/linkage_geometry.py (whose primitive
classes and shared interface constants it imports). It defines every
dimension, derives the drive-train stations, emits each part as an ordered
list of primitive booleans, and self-checks every mating clearance
analytically.

Consumers:
    gripper.py                 Fusion wrapper: replays the primitive lists
                               through TemporaryBRepManager and exports.
    gripper_parameters.yaml    the design parameters (this module only holds
                               purchased-hardware dimensions and derivations).

Local frame: x = 0 is the TCP plane (the forearm tip plate's outer face),
+X points away from the arm along the tool axis, Y is the jaw-travel axis,
Z is "up" (lid side). In the arm's world frame at the reference pose this
frame sits at (l_upper + l_fore, 0, shoulder_z) with the same orientation.

Architecture (SG-90 servo + rack-and-pinion; replaces the v1 NEMA 8 +
rotating-lead-screw drive — see README.md):

  An SG-90 micro servo is bench-screwed nose-first to a printed BULKHEAD
  PLATE (its two mounting-tab self-tappers), output shaft on the tool axis
  pointing +X. The plate slides down vertical grooves in the housing side
  walls and is captured by the lid — the whole servo cartridge drops in
  from the top, no fasteners into the housing.

  The PINION is a printed lantern gear: a flange pressed onto the servo's
  21T spline (Ø4.5 bore over the Ø4.8 spline broaches on assembly; the
  servo's own horn screw retains it) carrying eight Ø4.5 pins on a Ø18
  pitch circle. Two RACKS — integrated into the jaw sliders, one above and
  one below the pinion — carry trochoidal tooth spaces generated by
  simulated hobbing: the pin-radius cutter is subtracted along the cycloid
  the pin centers trace in each rack's frame (the same construction the
  cycloidal gearbox generator uses for its discs). Pin gearing is exact
  conjugate action with no undercut at this tooth count, and every tooth
  is a vertical-walled prism the printer handles cleanly.

  Opposite rack velocities give symmetric jaw motion: 18 mm of rack travel
  per jaw (~115 degrees of servo rotation) opens the jaws 0-36 mm. The
  servo is its own absolute position reference, so v1's homing microswitch
  is gone. NOT self-locking: grip needs the servo powered (README).

  Mounting contract (unchanged from v1 — the printed forearm is NOT
  touched): the back plate bolts with 4 x M3 x 8 on the Ø16 BCD into the
  forearm tip plate's outer-face inserts; a Ø10.3 pilot boss registers in
  the plate's Ø10.5 bore and passes the servo lead out through its Ø7
  center hole to the plate's bottom-edge wire notch.
"""

