def grid_volume_mm3(part, step=2.0):
    """Coarse voxel volume for the mass budget (±10-15 %)."""
    lo, hi = part.bbox()
    n = 0
    x = lo[0] + step / 2
    while x < hi[0]:
        y = lo[1] + step / 2
        while y < hi[1]:
            z = lo[2] + step / 2
            while z < hi[2]:
                if part.contains((x, y, z)):
                    n += 1
                z += step
            y += step
        x += step
    return n * step ** 3


def mass_estimate(d):
    """Printed parts via voxel volume + purchased hardware, in grams."""
    printed = 0.0
    for name, part in d['parts'].items():
        v = grid_volume_mm3(part)
        qty = 2 if name in ('rt_grip_pad',) else 1
        dens = 1.2e-3 if name == 'rt_grip_pad' else PETG_DENSITY * PRINT_FILL
        printed += qty * v * dens
    hardware = (SG90_MASS_G                # servo + lead
                + 7.0)                     # M3 mount/lid screws, tab screws
    return printed, hardware


