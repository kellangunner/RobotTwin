# SG-90 9 g micro servo (TowerPro and clones). Long case dimension is
# mounted along Z (nose up during the drop-in, shaft along +X in service).
# Clone envelopes vary ~±0.3 mm; the pockets carry clearance for that.
SG90_L = 22.8                   # case length (along Z here)
SG90_W = 12.4                   # case width (along Y)
SG90_SHAFT_OFF = 5.9            # shaft axis from the gearhead end of the case
SG90_NOSE = 4.0                 # mounting-tab face -> case top (through the plate)
SG90_BEHIND_TAB = 19.2          # mounting-tab face -> case back (incl. the tab)
SG90_TAB_L = 4.7                # each tab beyond the case end
SG90_TAB_T = 2.5
SG90_HOLE_OFF = 2.4             # tab hole center beyond the case end
SG90_SPLINE_D = 4.8             # 21T output spline
SG90_SPLINE_H = 4.0
SG90_STALL_NM = 0.176           # 1.8 kg*cm at 4.8 V
SG90_MASS_G = 10.5              # with lead
SG90_TAP_D = 1.8                # pilot holes for the tab self-tappers

SPLINE_SCREW_L = 8.0            # the servo's own horn screw (~M2 x 8)
SPLINE_SCREW_CLEAR = 2.5
SPLINE_SCREW_HEAD_D = 4.0

PETG_DENSITY = 1.27e-3          # g/mm^3
PRINT_FILL = 0.55               # effective density factor (walls + 30 % infill)

HOB_STEP_RAD = 0.04             # cam-angle step of the rack hobbing sweep
HOB_PHI_MAX = 1.0               # pin engagement half-angle swept per tooth
HOB_MARGIN_RAD = 0.35           # hob overtravel beyond the jaw stroke


