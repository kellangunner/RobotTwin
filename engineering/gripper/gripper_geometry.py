def stations(p):
    d, j, b = p['drive'], p['jaws'], p['body']
    st = {}
    st['clr'] = b['slide_clearance']
    st['gap'] = b['running_gap']

    # -- pin gearing --
    st['n_pins'] = int(d['pin_count'])
    st['r'] = d['pitch_radius']                      # pitch radius = jaw lever
    st['pin_r'] = d['pin_d'] / 2.0
    st['cutter_r'] = st['pin_r'] + d['profile_clearance']
    st['travel'] = j['max_opening'] / 2.0            # stroke per jaw
    st['rot'] = st['travel'] / st['r']               # servo swing, rad
    st['rot_deg'] = math.degrees(st['rot'])
    st['pitch'] = 2 * math.pi * st['r'] / st['n_pins']

    # -- axial stations, back plate to fingertip --
    st['back_t'] = b['back_thickness']
    st['boss_l'] = 4.0                               # pilot boss into the plate bore
    st['boss_d'] = T8_BORE_D - 0.2
    st['wire_d'] = 7.0
    st['bay0'] = st['back_t'] + 1.0                  # mount heads live in the gap
    st['case_back'] = st['back_t'] + 3.0
    st['bp0'] = st['case_back'] + SG90_BEHIND_TAB    # bulkhead plate, back face
    st['bp_t'] = 3.4                                 # < SG90_NOSE: tabs clamp it
    st['bp1'] = st['bp0'] + st['bp_t']
    st['case_top'] = st['bp0'] + SG90_NOSE           # 0.6 proud of the plate
    st['spline_x1'] = st['case_top'] + SG90_SPLINE_H
    st['flange_x0'] = st['bp1'] + 1.0
    st['flange_t'] = 3.0
    st['flange_x1'] = st['flange_x0'] + st['flange_t']
    st['flange_d'] = 2 * (st['r'] + st['pin_r'])     # pins tangent to the rim
    st['pin_x0'] = st['flange_x1']
    st['pin_x1'] = st['pin_x0'] + d['pin_length']
    st['rx0'] = st['pin_x0'] + 0.5                   # rack tooth band (inside pins)
    st['rx1'] = st['pin_x1'] - 0.5
    st['riser_x0'] = st['pin_x1'] + 0.5
    st['riser_x1'] = st['riser_x0'] + 3.9
    st['jb0'] = st['pin_x1'] + 1.4                   # jaw head block
    st['cav_x1'] = st['jb0'] + 9.0                   # carrier tunnel front
    st['fp1'] = st['cav_x1'] + 3.0                   # face plate = housing front
    st['finger_x1'] = st['fp1'] + j['finger_length']
    st['extent'] = st['finger_x1']                   # reach beyond the TCP

    # -- rack tooth geometry (mirrored bands above/below the pinion) --
    st['tip_z'] = st['r'] - 2.3                      # tooth tip plane (addendum)
    st['core_r'] = st['tip_z'] - 1.0                 # pinion core clears the tips
    st['root_z'] = st['r'] + st['cutter_r']          # deepest hob reach
    st['bar_back'] = st['root_z'] + 4.5              # solid backing behind roots

    # -- housing cross-section --
    st['out_hw'] = FA_PLATE_HALF
    st['int_hw'] = st['out_hw'] - b['wall']
    st['head_hw'] = 28.0
    st['floor_z1'] = -st['bar_back'] - st['gap']     # lower rack rides the floor
    st['floor_z0'] = st['floor_z1'] - 3.5
    st['roof_z'] = 22.0                              # wall tops / lid seat
    st['lid_z1'] = st['roof_z'] + 3.0
    st['win_x0'] = st['rx0'] - 0.2                   # walls end; bars sweep here
    st['rib_x0'] = st['rx0'] - 0.1                   # lid rib backs the upper rack
    st['rib_x1'] = st['riser_x0'] - 0.8
    st['rib_z0'] = st['bar_back'] + st['gap']
    st['tun_z0'], st['tun_z1'] = -11.35, 3.35        # carrier tunnel
    st['head_top'] = 6.0
    st['fp_slot_hz'] = 4.0                           # face-plate slot half height

    # -- bulkhead plate (servo cartridge) --
    st['bp_hw'] = st['int_hw'] + 1.8                 # engages 1.8 into each groove
    st['groove_hw'] = st['int_hw'] + 2.0
    st['bp_z0'] = st['floor_z1'] + 0.1
    st['bp_z1'] = st['roof_z'] - 0.2                 # lid captures the top edge
    st['win_hw'] = SG90_W / 2 + 0.3                  # nose window in the plate
    st['win_z0'] = -SG90_SHAFT_OFF - 0.3
    st['win_z1'] = SG90_L - SG90_SHAFT_OFF + 0.3
    st['tab_z_lo'] = -(SG90_SHAFT_OFF + SG90_HOLE_OFF)
    st['tab_z_hi'] = SG90_L - SG90_SHAFT_OFF + SG90_HOLE_OFF
    st['tab_tip_lo'] = -SG90_SHAFT_OFF - SG90_TAB_L
    st['tab_tip_hi'] = SG90_L - SG90_SHAFT_OFF + SG90_TAB_L

    # -- jaw sliders (modeled at the OPEN pose) --
    st['jaw_open_off'] = st['travel']
    st['fin_y0_closed'] = j['pad_proud']             # pads meet at y = 0
    st['car_y0'] = st['fin_y0_closed'] + st['travel']
    st['car_len'] = j['carrier_length']
    st['car_x0'], st['car_x1'] = st['jb0'] + 0.5, st['cav_x1'] - 0.5
    st['fin_t'] = j['finger_thickness']
    st['fin_h'] = j['finger_height']
    st['pad_t'] = j['pad_thickness']
    st['pad_proud'] = j['pad_proud']
    st['riser_y0_rel'] = 11.0                        # riser band on the carrier
    st['riser_y1_rel'] = 17.0
    st['bar_tip_y'] = -9.0                           # inner end of the rack bar
    # outermost hob reach — teeth must end before the riser
    st['hob_y_max'] = (st['r'] * math.sin(HOB_PHI_MAX)
                      + st['r'] * (st['rot'] + HOB_MARGIN_RAD))

    # -- performance --
    eff = d['mesh_efficiency']
    st['f_jaw'] = d['servo_torque_nm'] * eff / (2 * st['r'] / 1000.0)
    st['f_jaw_stall'] = SG90_STALL_NM * eff / (2 * st['r'] / 1000.0)
    # cantilevered pin root bending at stall, worst single-pin contact
    pin_arm = (st['rx0'] + st['rx1']) / 2 - st['pin_x0']
    st['pin_sigma'] = (st['f_jaw_stall'] * pin_arm * 32.0
                      / (math.pi * (2 * st['pin_r']) ** 3))
    st['servo_travel_deg'] = d['servo_travel_deg']
    return st


# ---------------------------------------------------------------------------
# Rack hobbing — pin-cutter sweep in each rack's frame (cycloid), the same
# construction the cycloidal gearbox uses for its disc profiles.
# ---------------------------------------------------------------------------

def rack_cutters(st, s):
    """Cutter centers (y, z) for the rack on side s (+1 above the pinion,
    -1 below), in the jaw's OPEN-pose frame. Rolling contact: rotation by
    theta about +X (positive = closing) puts a pin of phase alpha at
    (-r sin(alpha+theta), r cos(alpha+theta)); the s=+1 rack translates
    -r*theta and the s=-1 rack +r*theta. Mapping the pin into the rack's
    open frame and sampling theta over the stroke (plus margin) traces the
    cycloid whose envelope is the conjugate tooth space — note d(y)/d(theta)
    vanishes at the cusp (pure rolling), which is what leaves the flanks
    standing next to each pocket."""
    r, n = st['r'], st['n_pins']
    phi0 = 0.0 if s > 0 else math.pi                 # engagement direction
    z_keep = st['tip_z'] - st['cutter_r'] - 0.5      # cutter must reach the bar
    out = []
    for jdx in range(-3, n + 4):
        alpha = 2 * math.pi * jdx / n
        t0 = max(-HOB_MARGIN_RAD, phi0 - HOB_PHI_MAX - alpha)
        t1 = min(st['rot'] + HOB_MARGIN_RAD, phi0 + HOB_PHI_MAX - alpha)
        if t1 <= t0:
            continue
        k = 0
        while True:
            th = t0 + k * HOB_STEP_RAD
            if th > t1:
                break
            k += 1
            phi = alpha + th
            y = -r * math.sin(phi) + s * r * th
            z = r * math.cos(phi)
            if s > 0 and z > z_keep:
                out.append((y, z))
            elif s < 0 and z < -z_keep:
                out.append((y, z))
    return out


def mesh_contact_gaps(st, poses=61, h=0.08):
    """Numeric drive-continuity audit: rasterize the hobbed tooth band and
    count stroke poses where NO pin bears on a flank in the closing (+y
    normal) or opening (-y) direction. Both counts must be zero — pin
    gearing has no analytic contact-ratio shortcut worth trusting here.
    Symmetric racks: auditing the s=+1 side covers both."""
    r, n = st['r'], st['n_pins']
    cr, pr = st['cutter_r'], st['pin_r']
    y0g, y1g = -14.0, 32.0
    z0g, z1g = st['tip_z'], st['root_z'] + 0.2
    ny, nz = int((y1g - y0g) / h), int((z1g - z0g) / h)
    solid = [[True] * nz for _ in range(ny)]
    for (cy, cz) in rack_cutters(st, +1):
        iy0 = max(0, int((cy - cr - y0g) / h))
        iy1 = min(ny, int((cy + cr - y0g) / h) + 1)
        for iy in range(iy0, iy1):
            dy2 = cr * cr - (y0g + iy * h - cy) ** 2
            if dy2 <= 0:
                continue
            dz = math.sqrt(dy2)
            for iz in range(max(0, int((cz - dz - z0g) / h)),
                            min(nz, int((cz + dz - z0g) / h) + 1)):
                solid[iy][iz] = False
    bad_close = bad_open = 0
    for i in range(poses):
        th = st['rot'] * i / (poses - 1)
        plus = minus = False
        for k in range(-2, n + 3):
            phi = 2 * math.pi * k / n + th
            py = -r * math.sin(phi) + r * th
            pz = r * math.cos(phi)
            if pz < st['tip_z'] - pr - 0.3:
                continue
            for iy in range(max(0, int((py - cr - 0.3 - y0g) / h)),
                            min(ny, int((py + cr + 0.3 - y0g) / h) + 1)):
                for iz in range(nz):
                    if not solid[iy][iz]:
                        continue
                    dy = y0g + iy * h - py
                    dz = z0g + iz * h - pz
                    dist = math.hypot(dy, dz)
                    if abs(dist - cr) < 1.6 * h:
                        if dy / dist > 0.25:
                            plus = True
                        if dy / dist < -0.25:
                            minus = True
            if plus and minus:
                break
        bad_close += 0 if plus else 1
        bad_open += 0 if minus else 1
    return bad_close, bad_open


