def _bcd45(r=T8_BCD / 2):
    c = r * math.cos(math.radians(45))
    return [(c, c), (c, -c), (-c, c), (-c, -c)]


def _lid_screw_xy(st):
    return [(12.0, 18.0), (12.0, -18.0), (30.0, 18.0), (30.0, -18.0),
            (st['fp1'] - 1.5, 14.0), (st['fp1'] - 1.5, -14.0)]


def build_body(st):
    """Housing: back plate with the pilot boss, floor, side walls with the
    bulkhead-plate grooves, jaw head with the carrier tunnel and face plate.
    The walls stop at the rack window (the bars sweep through free air
    there); the lid's rib and the floor are the rack back-up rails. The
    servo cartridge and the pinion drop in from the open top."""
    p = Part('rt_grip_body')
    ihw, ohw = st['int_hw'], st['out_hw']
    p.add(Box(0, st['back_t'], -ohw, ohw, -ohw, ohw))            # back plate
    p.add(Cyl((-st['boss_l'], 0, 0), (0.05, 0, 0), st['boss_d']))  # pilot boss
    p.add(Box(st['back_t'], st['fp1'], -ohw, ohw,
              st['floor_z0'], st['floor_z1']))                   # floor
    for s in (+1, -1):
        p.add(Box(st['back_t'], st['win_x0'], s * ihw, s * ohw,
                  st['floor_z1'], st['roof_z']))                 # side walls
    p.add(Box(st['jb0'], st['fp1'], -st['head_hw'], st['head_hw'],
              st['floor_z1'], st['head_top']))                   # jaw head
    p.add(Box(st['cav_x1'], st['fp1'], -st['head_hw'], st['head_hw'],
              st['floor_z1'], st['head_top'] + 2.0))             # face plate low
    p.add(Box(st['cav_x1'], st['fp1'], -ohw, ohw,
              st['head_top'] + 2.0, st['roof_z']))               # face plate up
    # --- cuts ---
    for y, z in _bcd45():                                        # mounting
        p.cut(Cyl((-1, y, z), (st['back_t'] + 0.1, y, z), M3_CLEAR_D))
        p.cut(Cyl((2.0, y, z), (st['back_t'] + 0.1, y, z), M3_CB_D))
    p.cut(Cyl((-st['boss_l'] - 0.2, 0, 0), (st['back_t'] + 0.1, 0, 0),
              st['wire_d']))                                     # servo lead
    for s in (+1, -1):                               # bulkhead plate grooves
        p.cut(Box(st['bp0'] - 0.2, st['bp1'] + 0.2, s * (ihw - 0.1),
                  s * st['groove_hw'], st['floor_z1'] - 0.1, st['roof_z'] + 0.1))
    # jaw head: carrier tunnel, face-plate slot, riser passages (top and
    # bottom — each rack's riser crosses the head band on its own level)
    p.cut(Box(st['jb0'], st['cav_x1'], -st['head_hw'] - 1, st['head_hw'] + 1,
              st['tun_z0'], st['tun_z1']))
    p.cut(Box(st['cav_x1'] - 0.1, st['fp1'] + 0.1, -st['head_hw'] - 1,
              st['head_hw'] + 1, -st['fp_slot_hz'], st['fp_slot_hz']))
    p.cut(Box(st['riser_x0'] - 0.2, st['riser_x1'] + 0.2, -st['head_hw'] - 1,
              st['head_hw'] + 1, st['tun_z1'] - 0.2, st['head_top'] + 0.1))
    p.cut(Box(st['riser_x0'] - 0.2, st['riser_x1'] + 0.2, -st['head_hw'] - 1,
              st['head_hw'] + 1, st['floor_z1'] + 0.1, st['tun_z0'] + 0.2))
    for x, y in _lid_screw_xy(st):                   # lid insert pockets
        p.cut(Cyl((x, y, st['roof_z'] - INSERT_POCKET),
                  (x, y, st['roof_z'] + 0.1), INSERT_D))
    return p


def build_lid(st):
    """Flat top plate, 6 x M3 into the body's insert pockets. A hanging rib
    over the rack window is the upper rack's back-up rail (it cannot live on
    the body: the servo cartridge and pinion drop in through that volume)."""
    p = Part('rt_grip_lid')
    p.add(Box(st['back_t'] + 1.0, st['fp1'], -st['out_hw'], st['out_hw'],
              st['roof_z'], st['lid_z1']))
    p.add(Box(st['rib_x0'], st['rib_x1'], -st['int_hw'], st['int_hw'],
              st['rib_z0'], st['roof_z'] + 0.5))
    for x, y in _lid_screw_xy(st):
        p.cut(Cyl((x, y, st['roof_z'] - 0.1), (x, y, st['lid_z1'] + 0.1),
                  M3_CLEAR_D))
        p.cut(Cyl((x, y, st['lid_z1'] - M3_HEAD_H), (x, y, st['lid_z1'] + 0.1),
                  M3_CB_D))
    return p


def build_bulkhead(st):
    """Servo cartridge plate: the SG-90 nose passes the center window, the
    two mounting-tab self-tappers bite the printed pilot holes above and
    below it. The loaded plate slides down the wall grooves and the lid
    captures its top edge. Grip reaction torque goes tab -> plate -> walls."""
    p = Part('rt_grip_bulkhead')
    p.add(Box(st['bp0'], st['bp1'], -st['bp_hw'], st['bp_hw'],
              st['bp_z0'], st['bp_z1']))
    p.cut(Box(st['bp0'] - 0.1, st['bp1'] + 0.1, -st['win_hw'], st['win_hw'],
              st['win_z0'], st['win_z1']))
    for z in (st['tab_z_lo'], st['tab_z_hi']):
        p.cut(Cyl((st['bp0'] - 0.1, 0, z), (st['bp1'] + 0.1, 0, z), SG90_TAP_D))
    return p


def build_pinion(st):
    """Lantern pinion: flange + core pressed onto the servo spline (Ø4.5
    bore broaches over the Ø4.8 21T spline), retained by the servo's horn
    screw down the core's center bore. Eight cantilevered pins are the
    teeth; both racks mesh the same pin cage 180 degrees apart. Prints
    flange-down, pins vertical, no supports."""
    p = Part('rt_grip_pinion')
    p.add(Cyl((st['flange_x0'], 0, 0), (st['flange_x1'], 0, 0), st['flange_d']))
    p.add(Cyl((st['flange_x0'], 0, 0), (st['pin_x1'], 0, 0), 2 * st['core_r']))
    for k in range(st['n_pins']):
        a = 2 * math.pi * k / st['n_pins']
        y, z = st['r'] * math.sin(a), st['r'] * math.cos(a)
        p.add(Cyl((st['flange_x1'] - 0.6, y, z), (st['pin_x1'], y, z),
                  2 * st['pin_r']))
    p.cut(Cyl((st['flange_x0'] - 0.1, 0, 0), (st['spline_x1'] + 0.2, 0, 0),
              SG90_SPLINE_D - 0.3))
    p.cut(Cyl((st['spline_x1'], 0, 0), (st['pin_x1'] + 0.1, 0, 0),
              SPLINE_SCREW_CLEAR))
    p.cut(Cyl((st['pin_x1'] - 1.5, 0, 0), (st['pin_x1'] + 0.1, 0, 0),
              SPLINE_SCREW_HEAD_D + 1.0))
    return p


def build_jaw(st, s):
    """One jaw slider, modeled at the OPEN pose: transverse carrier in the
    head tunnel, neck through the face-plate slot, finger with the TPU pad
    pocket, and the rack: a toothed bar in the window band (above the
    pinion for s = +1, below for s = -1), an outer arm past the pin cage,
    and a riser through its head passage down/up to the carrier."""
    name = 'rt_grip_jaw_p' if s > 0 else 'rt_grip_jaw_n'
    p = Part(name)
    fy0 = st['car_y0']                               # finger inner face (open)
    car_y1 = fy0 + st['car_len']
    ry0, ry1 = fy0 + st['riser_y0_rel'], fy0 + st['riser_y1_rel']
    if s > 0:
        bar_z = (st['tip_z'], st['bar_back'])
        riser_z = (st['tun_z1'] - st['clr'] - 0.2, st['bar_back'])
    else:
        bar_z = (-st['bar_back'], -st['tip_z'])
        riser_z = (-st['bar_back'], st['tun_z0'] + st['clr'] + 1.0)
    p.add(Box(st['rx0'], st['rx1'], s * st['bar_tip_y'], s * ry1,
              bar_z[0], bar_z[1]))                   # toothed bar
    p.add(Box(st['rx1'] - 0.5, st['riser_x1'], s * ry0, s * ry1,
              bar_z[0], bar_z[1]))                   # outer arm past the pins
    p.add(Box(st['riser_x0'], st['riser_x1'], s * ry0, s * ry1,
              riser_z[0], riser_z[1]))               # riser to the carrier
    p.add(Box(st['car_x0'], st['car_x1'], s * fy0, s * car_y1,
              st['tun_z0'] + st['clr'], st['tun_z1'] - st['clr']))
    p.add(Box(st['car_x1'] - 0.1, st['fp1'], s * fy0, s * (fy0 + st['fin_t'] + 3),
              -st['fp_slot_hz'] + st['clr'], st['fp_slot_hz'] - st['clr']))
    p.add(Box(st['fp1'], st['finger_x1'], s * fy0, s * (fy0 + st['fin_t']),
              st['tun_z0'] + st['clr'], st['tun_z0'] + st['clr'] + st['fin_h']))
    # pad pocket, 1 mm deep, on the gripping face
    p.cut(Box(st['fp1'] + 3, st['finger_x1'] - 1, s * (fy0 - 0.1), s * (fy0 + 1.0),
              st['tun_z0'] + 2, st['tun_z0'] + st['fin_h'] - 1))
    # hob the tooth spaces
    for y, z in rack_cutters(st, s):
        p.cut(Cyl((st['rx0'] - 0.15, y, z), (st['rx1'] + 0.15, y, z),
                  2 * st['cutter_r']))
    return p


def build_pad(st):
    """TPU pad (print 2): drops into the finger pocket, 1 mm keyed + proud."""
    p = Part('rt_grip_pad')
    p.add(Box(0, st['finger_x1'] - st['fp1'] - 4, 0,
              st['pad_t'], 0, st['fin_h'] - 3))
    return p


# ---------------------------------------------------------------------------
# Hardware solids (audit / assembly visualization only)
# ---------------------------------------------------------------------------

def servo_solid(st):
    p = Part('hw_servo')
    p.add(Box(st['case_back'], st['case_top'], -SG90_W / 2, SG90_W / 2,
              -SG90_SHAFT_OFF, SG90_L - SG90_SHAFT_OFF))
    for z0, z1 in ((st['tab_tip_lo'], -SG90_SHAFT_OFF),
                   (SG90_L - SG90_SHAFT_OFF, st['tab_tip_hi'])):
        p.add(Box(st['bp0'] - SG90_TAB_T, st['bp0'], -SG90_W / 2, SG90_W / 2,
                  z0, z1))
    p.add(Cyl((st['case_top'], 0, 0), (st['spline_x1'], 0, 0), SG90_SPLINE_D))
    return p


