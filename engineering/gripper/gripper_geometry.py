# Parameters — gripper_parameters.yaml is the only source.
# Same minimal 'Section: / key: number' parser as the gearbox generator.
# ---------------------------------------------------------------------------

def yaml_path():
    return os.path.join(_HERE, 'gripper_parameters.yaml')


def read_params():
    with open(yaml_path(), 'r', encoding='utf-8') as f:
        lines = f.read().splitlines()
    data, section = {}, None
    for ln in lines:
        ln = ln.split('#', 1)[0].rstrip()
        if not ln.strip():
            continue
        m = re.match(r'^(\S[^:]*):\s*$', ln)
        if m:
            section = m.group(1).strip()
            data[section] = {}
            continue
        m = re.match(r'^\s+([A-Za-z_][\w]*)\s*:\s*([-0-9.]+)\s*$', ln)
        if m and section:
            data[section][m.group(1)] = float(m.group(2))
    return data


